import Foundation
import GuestChannel

/// Where a Mac's keys are on a PC keyboard: the scancode that the key in the same place sends.
///
/// QEMU takes keys by their place (its extended key event), so a key types whatever the guest's
/// keyboard layout puts there, as it would on a PC with that layout. Keys that come after 0xE0 on a PC
/// have that byte's high bit on the second one, the way QEMU numbers them.
///
/// Command is the Windows key, Option is Alt, and Control is Control.
public enum PCKeys {
    /// The PC scancode of the Mac key with this key code, if a PC keyboard has one there.
    public static func scancode(forMacKey code: UInt16) -> UInt16? {
        table[code]
    }

    private static let table: [UInt16: UInt16] = [
        // Letters
        0x00: 0x1E, 0x0B: 0x30, 0x08: 0x2E, 0x02: 0x20, 0x0E: 0x12, 0x03: 0x21, 0x05: 0x22, 0x04: 0x23,
        0x22: 0x17, 0x26: 0x24, 0x28: 0x25, 0x25: 0x26, 0x2E: 0x32, 0x2D: 0x31, 0x1F: 0x18, 0x23: 0x19,
        0x0C: 0x10, 0x0F: 0x13, 0x01: 0x1F, 0x11: 0x14, 0x20: 0x16, 0x09: 0x2F, 0x0D: 0x11, 0x07: 0x2D,
        0x10: 0x15, 0x06: 0x2C,
        // Digits
        0x12: 0x02, 0x13: 0x03, 0x14: 0x04, 0x15: 0x05, 0x17: 0x06, 0x16: 0x07, 0x1A: 0x08, 0x1C: 0x09,
        0x19: 0x0A, 0x1D: 0x0B,
        // Punctuation
        0x1B: 0x0C, 0x18: 0x0D, 0x21: 0x1A, 0x1E: 0x1B, 0x2A: 0x2B, 0x29: 0x27, 0x27: 0x28, 0x32: 0x29,
        0x2B: 0x33, 0x2F: 0x34, 0x2C: 0x35,
        // The key next to Shift on an ISO keyboard, and the two a Japanese one adds.
        0x0A: 0x56, 0x5D: 0x7D, 0x5E: 0x73,
        // Whitespace and editing
        0x24: 0x1C, 0x30: 0x0F, 0x31: 0x39, 0x33: 0x0E, 0x35: 0x01, 0x75: 0xD3, 0x72: 0xD2,
        0x73: 0xC7, 0x77: 0xCF, 0x74: 0xC9, 0x79: 0xD1,
        // Arrows
        0x7B: 0xCB, 0x7C: 0xCD, 0x7D: 0xD0, 0x7E: 0xC8,
        // Modifiers
        0x38: 0x2A, 0x3C: 0x36, 0x3B: 0x1D, 0x3E: 0x9D, 0x3A: 0x38, 0x3D: 0xB8, 0x37: 0xDB, 0x36: 0xDC,
        0x39: 0x3A,
        // Function keys
        0x7A: 0x3B, 0x78: 0x3C, 0x63: 0x3D, 0x76: 0x3E, 0x60: 0x3F, 0x61: 0x40, 0x62: 0x41, 0x64: 0x42,
        0x65: 0x43, 0x6D: 0x44, 0x67: 0x57, 0x6F: 0x58,
        // F13 to F15 are where a PC has Print Screen, Scroll Lock and Pause.
        0x69: 0xB7, 0x6B: 0x46, 0x71: 0xC6,
        // Keypad
        0x52: 0x52, 0x53: 0x4F, 0x54: 0x50, 0x55: 0x51, 0x56: 0x4B, 0x57: 0x4C, 0x58: 0x4D, 0x59: 0x47,
        0x5B: 0x48, 0x5C: 0x49, 0x41: 0x53, 0x43: 0x37, 0x45: 0x4E, 0x4E: 0x4A, 0x4B: 0xB5, 0x4C: 0x9C,
        0x51: 0x59, 0x47: 0x45,
    ]

    /// The scancodes to press for `press`, which names keys as a Mac has them: the held keys first,
    /// then the key.
    public static func scancodes(for press: MacKeys.Press) throws -> (held: [UInt16], key: UInt16?) {
        let held = try press.modifiers.map { modifier -> UInt16 in
            guard let code = scancode(forMacKey: modifier.key) else { throw MachineKeyError.noSuchKey }
            return code
        }
        guard let key = press.key else { return (held, nil) }
        guard let code = scancode(forMacKey: key) else { throw MachineKeyError.noSuchKey }
        return (held, code)
    }

    enum MachineKeyError: Error {
        case noSuchKey
    }
}
