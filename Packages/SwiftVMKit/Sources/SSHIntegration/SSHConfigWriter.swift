import Foundation

/// One `Host` block in the generated SSH configuration.
public struct SSHHostEntry: Sendable, Hashable {
    public var alias: String
    public var hostName: String
    public var user: String?
    public var port: UInt16
    public var identityFile: String?

    public init(alias: String, hostName: String, user: String? = nil, port: UInt16 = 22, identityFile: String? = nil) {
        self.alias = alias
        self.hostName = hostName
        self.user = user
        self.port = port
        self.identityFile = identityFile
    }
}

/// Generates the SSH configuration that makes `ssh <machine-alias>` work from any terminal.
///
/// SwiftVM owns one generated file and, with the user's consent, adds a single `Include` line for it at the
/// top of `~/.ssh/config`. Nothing else in the user's configuration is touched.
public struct SSHConfigWriter: Sendable {
    /// The generated file listing every machine.
    public let generatedConfigURL: URL
    /// Host keys of guests, kept apart from the user's own `known_hosts`.
    public let knownHostsURL: URL
    /// The user's own SSH configuration.
    public let userConfigURL: URL

    public init(
        generatedConfigURL: URL,
        knownHostsURL: URL? = nil,
        userConfigURL: URL = URL.homeDirectory.appending(path: ".ssh/config")
    ) {
        self.generatedConfigURL = generatedConfigURL
        self.knownHostsURL = knownHostsURL ?? generatedConfigURL.deletingLastPathComponent().appending(path: "known_hosts")
        self.userConfigURL = userConfigURL
    }

    // MARK: Generated file

    /// Renders the generated configuration for `entries`.
    ///
    /// Guest host keys are recorded in `knownHostsURL` on first connection and verified afterwards.
    public static func render(_ entries: [SSHHostEntry], knownHostsURL: URL) -> String {
        var lines = [
            "# Generated by SwiftVM. Changes are overwritten.",
            "# Each virtual machine is reachable as: ssh <alias>",
        ]
        for entry in entries.sorted(by: { $0.alias < $1.alias }) where isValidAlias(entry.alias) {
            lines.append("")
            lines.append("Host \(entry.alias)")
            lines.append("    HostName \(entry.hostName)")
            if let user = entry.user, !user.isEmpty {
                lines.append("    User \(user)")
            }
            if entry.port != 22 {
                lines.append("    Port \(entry.port)")
            }
            if let identityFile = entry.identityFile, !identityFile.isEmpty {
                lines.append("    IdentityFile \(quoted(identityFile))")
                lines.append("    IdentitiesOnly yes")
            }
            lines.append("    HostKeyAlias \(entry.alias)")
            lines.append("    StrictHostKeyChecking accept-new")
            lines.append("    UserKnownHostsFile \(quoted(knownHostsURL.path))")
        }
        return lines.joined(separator: "\n") + "\n"
    }

    /// Writes the generated configuration. Does nothing if the content is unchanged.
    public func write(_ entries: [SSHHostEntry]) throws {
        let content = Self.render(entries, knownHostsURL: knownHostsURL)
        if let existing = try? String(contentsOf: generatedConfigURL, encoding: .utf8), existing == content {
            return
        }
        try FileManager.default.createDirectory(at: generatedConfigURL.deletingLastPathComponent(), withIntermediateDirectories: true)
        try content.write(to: generatedConfigURL, atomically: true, encoding: .utf8)
        try FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: generatedConfigURL.path)
    }

    /// Forgets the recorded host key of `alias`, e.g. after its machine was deleted or reinstalled.
    public func forgetHostKey(for alias: String) {
        guard let content = try? String(contentsOf: knownHostsURL, encoding: .utf8) else { return }
        let kept = Self.lines(of: content).filter { line in
            guard let hosts = line.split(separator: " ").first else { return true }
            return !hosts.split(separator: ",").contains { $0 == alias }
        }
        try? kept.joined(separator: "\n").write(to: knownHostsURL, atomically: true, encoding: .utf8)
    }

    // MARK: Include line

    var includeLine: String { "Include \(Self.quoted(generatedConfigURL.path))" }

    /// Whether `~/.ssh/config` already includes the generated file.
    public var isIncludeInstalled: Bool {
        guard let content = try? String(contentsOf: userConfigURL, encoding: .utf8) else { return false }
        return Self.lines(of: content).contains { $0.trimmingCharacters(in: .whitespaces) == includeLine }
    }

    /// Adds the `Include` line at the top of `~/.ssh/config`, creating the file if needed.
    ///
    /// `Include` must come before the first `Host` block to apply globally, so it is inserted at the top.
    public func installInclude() throws {
        guard !isIncludeInstalled else { return }
        let fileManager = FileManager.default
        let directory = userConfigURL.deletingLastPathComponent()
        if !fileManager.fileExists(atPath: directory.path) {
            try fileManager.createDirectory(at: directory, withIntermediateDirectories: true, attributes: [.posixPermissions: 0o700])
        }
        let existing = (try? String(contentsOf: userConfigURL, encoding: .utf8)) ?? ""
        let header = "# Added by SwiftVM: hosts for virtual machines\n\(includeLine)\n"
        let updated = existing.isEmpty ? header : header + "\n" + existing
        try updated.write(to: userConfigURL, atomically: true, encoding: .utf8)
        try fileManager.setAttributes([.posixPermissions: 0o600], ofItemAtPath: userConfigURL.path)
    }

    /// Removes the `Include` line (and its comment) from `~/.ssh/config`, leaving everything else as is.
    public func removeInclude() throws {
        guard let existing = try? String(contentsOf: userConfigURL, encoding: .utf8) else { return }
        var lines = Self.lines(of: existing)
        guard let index = lines.firstIndex(where: { $0.trimmingCharacters(in: .whitespaces) == includeLine }) else { return }
        lines.remove(at: index)
        if index > 0, lines[index - 1].hasPrefix("# Added by SwiftVM") {
            lines.remove(at: index - 1)
            // Drop the blank separator line that was inserted after the header.
            if index - 1 < lines.count, lines[index - 1].isEmpty {
                lines.remove(at: index - 1)
            }
        }
        try lines.joined(separator: "\n").write(to: userConfigURL, atomically: true, encoding: .utf8)
        try FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: userConfigURL.path)
    }

    // MARK: Helpers

    static func isValidAlias(_ alias: String) -> Bool {
        !alias.isEmpty && alias.allSatisfy { $0.isASCII && ($0.isLetter || $0.isNumber || $0 == "-" || $0 == "_" || $0 == ".") }
    }

    static func quoted(_ path: String) -> String {
        path.contains(" ") ? "\"\(path)\"" : path
    }

    private static func lines(of content: String) -> [String] {
        content.components(separatedBy: "\n")
    }
}
